"""Workspace model: the on-disk home of one plotting session (design.md §4).

The workspace directory is the **only** coupling between better-mad and the agent:

    workspace/
    ├── AGENTS.md      # skill file for the agent harness (SDK reference, rules)
    ├── datasets.md    # auto-generated manifest of loaded datasets
    ├── plot.py        # the active plotting script (agent- and user-edited)
    └── .data/         # per-dataset parquet snapshots + .json sidecars (source path,
                        # parser settings), consumed by better_mad.sdk; browser
                        # uploads also keep a raw copy under .data/sources/
                        # (M3.5: their sidecars point there, so re-parse and
                        # reload-from-disk survive restarts)

The app watches ``plot.py`` and re-runs it (see :mod:`better_mad.core.runner`);
agent harnesses discover the SDK by reading ``AGENTS.md``. Nothing here touches the UI.
"""

from __future__ import annotations

import json
import os
import shutil
import time
from dataclasses import asdict, dataclass, field
from importlib import resources
from pathlib import Path

import pandas as pd

from better_mad.core.dataset import Dataset, load_dataset
from better_mad.core.loading import ParserSettings

SCRIPT_NAME = "plot.py"
SKILL_FILE = "AGENTS.md"
MANIFEST_FILE = "datasets.md"
DATA_DIR_NAME = ".data"
SOURCES_DIR_NAME = "sources"  # raw copies of browser uploads (handoff M3.5 §6.1)

STARTER_SCRIPT = '''\
"""Plot script — edited by you and the agent; re-runs automatically on save.

See AGENTS.md for the SDK reference and datasets.md for available data.
"""

# import holoviews as hv
#
# import better_mad.sdk as bm
#
# df = bm.data("<dataset name>")  # see datasets.md for names and columns
# fig = hv.Points(df, kdims=["XCORD_MIDPT", "YCORD_MIDPT"])
# bm.show(fig)
'''

_MANIFEST_HEADER = """\
# Datasets

Auto-generated by better-mad — do not edit. Script names are the column names
`bm.data()` returns; originals are shown for reference.

"""

_MANIFEST_EMPTY = _MANIFEST_HEADER + "No datasets loaded yet.\n"


def _skill_template() -> str:
    return resources.files("better_mad.core.templates").joinpath("AGENTS.md").read_text()


def _dump_sidecar(ds: Dataset) -> str:
    """Serialize a dataset's source path and parser settings to sidecar JSON text."""
    payload = {"source": str(ds.path.resolve()), "settings": asdict(ds.settings)}
    return json.dumps(payload, indent=2)


def _load_sidecar(sidecar: Path, fallback_path: Path) -> tuple[Path, ParserSettings]:
    """Read a sidecar written by :func:`_dump_sidecar`.

    A missing or unparseable sidecar degrades to ``fallback_path`` with default
    settings; never raises (errors degrade, they don't crash the open).
    """
    try:
        data = json.loads(sidecar.read_text())
        raw = data["settings"]
        settings = ParserSettings(
            delimiter=raw["delimiter"],
            decimal=raw["decimal"],
            sentinels=tuple(raw["sentinels"]),
            comment=raw["comment"],
            float64_columns=(
                tuple(raw["float64_columns"]) if raw["float64_columns"] is not None else None
            ),
        )
        return Path(data["source"]), settings
    except Exception:  # missing file, bad JSON or wrong shape -> fall back
        return fallback_path, ParserSettings()


@dataclass
class Workspace:
    """A plotting workspace on disk.

    Attributes:
        path: workspace directory.
        datasets: name -> loaded dataset. Names are file stems, de-duplicated
            with ``_2``, ``_3`` suffixes.
    """

    path: Path
    datasets: dict[str, Dataset] = field(default_factory=dict)

    @property
    def script_path(self) -> Path:
        return self.path / SCRIPT_NAME

    @property
    def skill_path(self) -> Path:
        return self.path / SKILL_FILE

    @property
    def manifest_path(self) -> Path:
        return self.path / MANIFEST_FILE

    @property
    def data_dir(self) -> Path:
        return self.path / DATA_DIR_NAME

    @property
    def sources_dir(self) -> Path:
        """``.data/sources`` — raw copies of browser uploads (M3.5 §6.1).

        Created on first use. CLI-loaded files are never copied here, and a
        registered upload's raw copy is deleted with the dataset (``remove``).
        """
        d = self.data_dir / SOURCES_DIR_NAME
        d.mkdir(parents=True, exist_ok=True)
        return d

    def add_file(self, path: str | Path, settings: ParserSettings | None = None) -> Dataset:
        """Load a file into the workspace: parse, snapshot to parquet + sidecar, refresh manifest.

        The dataset name is the file stem; on collision a numeric suffix is added.
        The source path is kept as-is (never copied — a CLI file belongs to the
        user). Raises ``LoaderError`` on unparsable input (nothing is registered).
        """
        ds = load_dataset(path, settings=settings)
        name = self._dedupe_name(ds.name)
        self._register(ds, name)
        return ds

    def add_upload(
        self, src: Path, original_name: str, settings: ParserSettings | None = None
    ) -> Dataset:
        """Register a browser upload: parse, persist a raw copy under ``.data/sources/``,
        snapshot to parquet + sidecar, refresh manifest (M3.5 §6.1, resolves W9).

        ``src`` is a temporary copy of the upload; ``original_name`` supplies the
        dataset name (file stem, deduped) and the persisted copy's suffix. On
        ``LoaderError`` nothing is registered and nothing is copied — the caller
        deletes ``src``. On success the dataset's source is the persisted copy,
        so re-parse and reload-from-disk survive restarts.
        """
        ds = load_dataset(src, settings=settings)  # LoaderError propagates untouched
        name = self._dedupe_name(ds.name)
        suffix = Path(original_name).suffix
        target = self.sources_dir / f"{name}{suffix}"  # named from the FINAL name (T6)
        shutil.copyfile(src, target)
        ds.path = target
        self._register(ds, name)
        return ds

    def reparse(self, name: str, settings: ParserSettings) -> Dataset:
        """Re-load a dataset from its source with new settings, in place (M3.5 §6.1).

        The parquet is overwritten atomically (tmp + ``os.replace`` — a
        concurrent worker ``bm.data()`` sees old-or-new, never truncated, T3),
        the sidecar is rewritten, the name is preserved even if columns changed,
        and the manifest is refreshed. Unknown name → ``KeyError``;
        ``LoaderError`` propagates with the dataset untouched.
        """
        if name not in self.datasets:
            raise KeyError(name)
        old = self.datasets[name]
        ds = load_dataset(old.path, settings=settings)  # LoaderError propagates
        ds.name = name
        tmp = self.data_dir / f"{name}.parquet.tmp"
        ds.df.to_parquet(tmp)
        os.replace(tmp, self.data_dir / f"{name}.parquet")  # atomic on one filesystem
        (self.data_dir / f"{name}.json").write_text(_dump_sidecar(ds))
        self.datasets[name] = ds
        self.refresh_manifest()
        return ds

    def remove(self, name: str) -> None:
        """Close a dataset: delete its parquet + sidecar, drop the entry, refresh
        the manifest (M3.5 §6.1).

        The raw source is deleted **only** when it resolves under ``sources_dir``
        (a persisted upload copy) — never a user's CLI file (trap T4). Unknown
        name → ``KeyError``.
        """
        if name not in self.datasets:
            raise KeyError(name)
        source = self.datasets.pop(name).path
        (self.data_dir / f"{name}.parquet").unlink(missing_ok=True)
        (self.data_dir / f"{name}.json").unlink(missing_ok=True)
        if _is_under(source, self.sources_dir):
            source.unlink(missing_ok=True)
        self.refresh_manifest()

    def dataset_head(self, name: str, lines: int = 20) -> str:
        """First ``lines`` lines of a dataset's raw source (M3.5 §6.1) — the
        settings-block preview. Text mode with ``errors="replace"``; a missing
        source raises ``FileNotFoundError`` (the hub maps it to 404-with-detail);
        unknown name → ``KeyError``.
        """
        if name not in self.datasets:
            raise KeyError(name)
        path = self.datasets[name].path
        with path.open("r", encoding="utf-8", errors="replace") as f:
            return "".join(f.readline() for _ in range(lines))

    def _dedupe_name(self, stem: str) -> str:
        name = stem
        n = 2
        while name in self.datasets:
            name = f"{stem}_{n}"
            n += 1
        return name

    def _register(self, ds: Dataset, name: str) -> None:
        """Shared registration tail of ``add_file``/``add_upload``: parquet snapshot,
        sidecar, in-memory entry, manifest refresh."""
        ds.name = name
        ds.df.to_parquet(self.data_dir / f"{name}.parquet")
        (self.data_dir / f"{name}.json").write_text(_dump_sidecar(ds))
        self.datasets[name] = ds
        self.refresh_manifest()

    def refresh_manifest(self) -> None:
        self.manifest_path.write_text(render_manifest(self.datasets))


def _is_under(path: Path, directory: Path) -> bool:
    """True when ``path`` resolves inside ``directory`` (both resolved)."""
    try:
        path.resolve().relative_to(directory.resolve())
    except ValueError:
        return False
    return True


def create_workspace(path: str | Path) -> Workspace:
    """Create (or open) a workspace directory.

    Writes the skill file, starter script and manifest where missing; never
    overwrites existing files, so user/agent edits survive re-open. Datasets
    found in ``.data`` are rehydrated so the manifest reflects the snapshots
    that ``better_mad.sdk`` serves.
    """
    root = Path(path)
    ws = Workspace(path=root)
    root.mkdir(parents=True, exist_ok=True)
    ws.data_dir.mkdir(exist_ok=True)
    _rehydrate_datasets(ws)
    if not ws.skill_path.exists():
        ws.skill_path.write_text(_skill_template())
    if not ws.script_path.exists():
        ws.script_path.write_text(STARTER_SCRIPT)
    ws.refresh_manifest()
    return ws


def _rehydrate_datasets(ws: Workspace) -> None:
    """Populate ``ws.datasets`` from the ``.data`` parquet snapshots.

    Source path and parser settings come from the ``.json`` sidecar when readable,
    else fall back to the snapshot path + default settings. A corrupt snapshot is
    skipped (errors degrade, never crash); orphan sidecars without a parquet are
    ignored by the glob.
    """
    for pq_file in sorted(ws.data_dir.glob("*.parquet")):
        name = pq_file.stem
        t0 = time.perf_counter()
        try:
            df = pd.read_parquet(pq_file)
        except Exception:  # corrupt/unreadable snapshot -> skip this dataset
            continue
        source, settings = _load_sidecar(pq_file.with_suffix(".json"), fallback_path=pq_file)
        ws.datasets[name] = Dataset(
            name=name,
            path=source,
            df=df,
            settings=settings,
            load_time_s=time.perf_counter() - t0,
            from_cache=True,
        )


def render_manifest(datasets: dict[str, Dataset]) -> str:
    """Render ``datasets.md``: per-dataset column tables with stats."""
    if not datasets:
        return _MANIFEST_EMPTY
    parts = [_MANIFEST_HEADER]
    for name, ds in datasets.items():
        parts.append(f"## {name}\n")
        parts.append(f"- Source: `{ds.path}`")
        parts.append(f"- Rows: {len(ds.df):,} · Columns: {len(ds.df.columns)}")
        parts.append("")
        parts.append("| Original | Script name | dtype | min | max | NaN% |")
        parts.append("|---|---|---|---|---|---|")
        display: dict[str, str] = ds.df.attrs.get("display_names", {})
        for col in ds.df.columns:
            parts.append(_column_row(ds.df, col, display.get(col, col)))
        parts.append("")
    return "\n".join(parts)


def _column_row(df: pd.DataFrame, col: str, original: str) -> str:
    s = df[col]
    dtype = str(s.dtype)
    nan_pct = 100.0 * s.isna().mean()
    if pd.api.types.is_numeric_dtype(s) and s.notna().any():
        lo = f"{s.min():.6g}"
        hi = f"{s.max():.6g}"
    else:
        lo = hi = "—"
    return f"| {original} | `{col}` | {dtype} | {lo} | {hi} | {nan_pct:.1f} |"
